-- ============================================================
-- queries.sql — SQL-запити для системи управління завданнями
-- ============================================================


-- ── Запит 1 ─────────────────────────────────────────────────────────────────
-- Отримати всі завдання певного користувача (за user_id)
-- Замініть 1 на потрібний id користувача
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    t.id,
    t.title,
    t.description,
    s.name AS status,
    u.fullname AS user
FROM tasks t
JOIN status s ON t.status_id = s.id
JOIN users  u ON t.user_id   = u.id
WHERE t.user_id = 1;


-- ── Запит 2 ─────────────────────────────────────────────────────────────────
-- Вибрати завдання за певним статусом (підзапит) — наприклад, 'new'
-- ─────────────────────────────────────────────────────────────────────────────
SELECT id, title, description
FROM tasks
WHERE status_id = (
    SELECT id FROM status WHERE name = 'new'
);


-- ── Запит 3 ─────────────────────────────────────────────────────────────────
-- Оновити статус конкретного завдання на 'in progress'
-- Замініть 1 на потрібний id завдання
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE tasks
SET status_id = (SELECT id FROM status WHERE name = 'in progress')
WHERE id = 1;


-- ── Запит 4 ─────────────────────────────────────────────────────────────────
-- Отримати список користувачів, які не мають жодного завдання
-- ─────────────────────────────────────────────────────────────────────────────
SELECT id, fullname, email
FROM users
WHERE id NOT IN (
    SELECT DISTINCT user_id FROM tasks
);


-- ── Запит 5 ─────────────────────────────────────────────────────────────────
-- Додати нове завдання для конкретного користувача
-- Замініть значення на потрібні
-- ─────────────────────────────────────────────────────────────────────────────
INSERT INTO tasks (title, description, status_id, user_id)
VALUES (
    'Нове тестове завдання',
    'Опис нового завдання, додане через INSERT',
    (SELECT id FROM status WHERE name = 'new'),
    1   -- id користувача
);


-- ── Запит 6 ─────────────────────────────────────────────────────────────────
-- Отримати всі завдання, які ще не завершено (статус ≠ 'completed')
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    t.id,
    t.title,
    s.name AS status,
    u.fullname AS user
FROM tasks t
JOIN status s ON t.status_id = s.id
JOIN users  u ON t.user_id   = u.id
WHERE s.name <> 'completed';


-- ── Запит 7 ─────────────────────────────────────────────────────────────────
-- Видалити конкретне завдання за його id
-- Замініть 1 на потрібний id завдання
-- ─────────────────────────────────────────────────────────────────────────────
DELETE FROM tasks
WHERE id = 1;


-- ── Запит 8 ─────────────────────────────────────────────────────────────────
-- Знайти користувачів з певною електронною поштою (LIKE)
-- Замініть '%@gmail.com' на потрібний шаблон
-- ─────────────────────────────────────────────────────────────────────────────
SELECT id, fullname, email
FROM users
WHERE email LIKE '%@gmail.com';


-- ── Запит 9 ─────────────────────────────────────────────────────────────────
-- Оновити ім'я користувача за id
-- Замініть значення на потрібні
-- ─────────────────────────────────────────────────────────────────────────────
UPDATE users
SET fullname = 'Іван Петренко'
WHERE id = 1;


-- ── Запит 10 ────────────────────────────────────────────────────────────────
-- Отримати кількість завдань для кожного статусу
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    s.name    AS status,
    COUNT(t.id) AS tasks_count
FROM status s
LEFT JOIN tasks t ON t.status_id = s.id
GROUP BY s.name
ORDER BY tasks_count DESC;


-- ── Запит 11 ────────────────────────────────────────────────────────────────
-- Отримати завдання, призначені користувачам з певним доменом email
-- Замініть '%@example.com' на потрібний домен
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    t.id,
    t.title,
    t.description,
    u.fullname,
    u.email
FROM tasks t
JOIN users u ON t.user_id = u.id
WHERE u.email LIKE '%@example.com';


-- ── Запит 12 ────────────────────────────────────────────────────────────────
-- Отримати список завдань, що не мають опису (description IS NULL)
-- ─────────────────────────────────────────────────────────────────────────────
SELECT id, title, user_id
FROM tasks
WHERE description IS NULL;


-- ── Запит 13 ────────────────────────────────────────────────────────────────
-- Вибрати користувачів та їхні завдання зі статусом 'in progress'
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    u.fullname,
    u.email,
    t.id   AS task_id,
    t.title
FROM users u
INNER JOIN tasks  t ON t.user_id   = u.id
INNER JOIN status s ON t.status_id = s.id
WHERE s.name = 'in progress'
ORDER BY u.fullname;


-- ── Запит 14 ────────────────────────────────────────────────────────────────
-- Отримати користувачів та кількість їхніх завдань (включно з тими,
-- у кого завдань немає — LEFT JOIN)
-- ─────────────────────────────────────────────────────────────────────────────
SELECT
    u.id,
    u.fullname,
    u.email,
    COUNT(t.id) AS tasks_count
FROM users u
LEFT JOIN tasks t ON t.user_id = u.id
GROUP BY u.id, u.fullname, u.email
ORDER BY tasks_count DESC;
